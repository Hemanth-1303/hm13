package com.xworkz.tilesapp.tiles;

public class Tiles {
        private String material;
        private String color;
        private String finishType;
        private double pricePerSquareFoot;
        private double size;
        private String brand;
        private String application;

        public void setMaterial(String material) {
            this.material = material;
        }

        public String getMaterial() {
            return material;
        }

        public void setColor(String color) {
            this.color = color;
        }

        public String getColor() {
            return color;
        }

        public void setFinishType(String finishType) {
            this.finishType = finishType;
        }

        public String getFinishType() {
            return finishType;
        }

        public void setPricePerSquareFoot(double pricePerSquareFoot) {
            this.pricePerSquareFoot = pricePerSquareFoot;
        }

        public double getPricePerSquareFoot() {
            return pricePerSquareFoot;
        }

        public void setSize(double size) {
            this.size = size;
        }

        public double getSize() {
            return size;
        }

        public void setBrand(String brand) {
            this.brand = brand;
        }

        public String getBrand() {
            return brand;
        }

        public void setApplication(String application) {
            this.application = application;
        }

        public String getApplication() {
            return application;
        }
    }


